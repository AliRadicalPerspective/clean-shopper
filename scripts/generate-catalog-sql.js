/**
 * Generate the catalog migration from the data modules.
 *
 * The seed is generated rather than hand-written so the database and
 * src/data/*.js cannot drift. Re-run it whenever the catalog changes:
 *
 *   npm run gen:catalog
 *
 * Applied by `supabase db push`, or by pasting into the SQL editor. The file is
 * idempotent — every insert is an upsert keyed on the primary key.
 */

import { writeFileSync } from 'node:fs'
import { CATEGORIES, PRODUCTS } from '../src/data/products.js'
import { INGREDIENT_LIST } from '../src/data/ingredients.js'
import { CERT_LIST } from '../src/data/certifications.js'
import { ARTICLES } from '../src/data/articles.js'

/** A SQL text literal, or NULL. */
const lit = (v) =>
  v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`

/** A text[] literal. Empty arrays are written explicitly, never as NULL. */
const arr = (values) =>
  !values || values.length === 0
    ? `'{}'::text[]`
    : `array[${values.map(lit).join(', ')}]::text[]`

const jsonb = (value) => `${lit(JSON.stringify(value))}::jsonb`

function upsert(table, key, rows, columns) {
  const names = columns.join(', ')
  const values = rows
    .map((row) => {
      const cells = columns.map((c) => {
        if (row[c] === undefined) {
          throw new Error(
            `${table}: no value for column "${c}". The column list and the row ` +
              `builder have drifted apart.`,
          )
        }
        return row[c]
      })
      return `  (${cells.join(', ')})`
    })
    .join(',\n')
  const updates = columns
    .filter((c) => c !== key)
    .map((c) => `    ${c} = excluded.${c}`)
    .join(',\n')

  return `insert into public.${table} (${names}) values\n${values}\non conflict (${key}) do update set\n${updates};\n`
}

const out = []

out.push(`-- Clean Shopper — catalog schema and seed
--
-- GENERATED by scripts/generate-catalog-sql.js. Do not edit by hand; edit the
-- modules under src/data/ and re-run \`npm run gen:catalog\`.
--
-- Run this in the Supabase dashboard: SQL Editor → New query → paste → Run.
-- It is idempotent, so re-running it is safe. The user_state migration runs
-- first; that one carries the table the app needs in order to boot.
--
-- Everything here is reference data: identical for every visitor, world-
-- readable, and never written from the browser. None of these tables has an
-- insert or update policy, so the anon key has no path to mutating them even
-- though it ships in the bundle.
`)

// ——————————————————————————————————————— Schema

out.push(`-- ——— Schema ————————————————————————————————————————————————

create table if not exists public.categories (
  id            text primary key,
  name          text not null,
  subcategories text[] not null default '{}',
  sort_order    smallint not null default 0
);

create table if not exists public.ingredients (
  id         text primary key,
  name       text not null,
  aliases    text[] not null default '{}',
  -- Avoidance is matched on family, never on a literal name: "no quats" has to
  -- catch benzalkonium chloride without the shopper naming it.
  family     text not null,
  level      text not null check (level in ('high', 'moderate', 'low', 'clear')),
  -- What a cleaning ingredient harms: the person using it, what is downstream
  -- of the drain, or both. Not the same question.
  dimension  text not null check (dimension in ('health', 'environment', 'both')),
  -- Travels with level on purpose. A verdict without its confidence is a lie of
  -- precision about genuinely contested science.
  confidence text not null check (confidence in ('strong', 'moderate', 'limited')),
  why        text not null
);

create index if not exists ingredients_family_idx on public.ingredients (family);

create table if not exists public.certifications (
  id     text primary key,
  name   text not null,
  body   text not null,
  -- The whole point of this table. An audited mark and a phrase a brand printed
  -- on its own bottle are different objects and are never rendered together.
  rigor  text not null check (rigor in ('third-party', 'self-declared')),
  covers text not null,
  what   text not null
);

create table if not exists public.products (
  id                text primary key,
  name              text not null,
  brand             text not null,
  category_id       text not null references public.categories (id),
  subcategory       text not null,
  tags              text[] not null default '{}',
  price             numeric(10, 2) not null,
  size              text not null,
  -- Ids into public.ingredients / certifications. Arrays rather than join
  -- tables: the app always reads a product whole, and at this size a join buys
  -- nothing but round trips.
  ingredient_ids    text[] not null default '{}',
  certification_ids text[] not null default '{}',
  claim_ids         text[] not null default '{}',
  -- Slot name in src/assets/images/index.js, or null for "no photograph yet".
  image             text,
  summary           text not null
);

create index if not exists products_category_idx on public.products (category_id, subcategory);
create index if not exists products_tags_idx on public.products using gin (tags);
create index if not exists products_ingredients_idx on public.products using gin (ingredient_ids);

create table if not exists public.articles (
  slug              text primary key,
  kicker            text not null,
  title             text not null,
  dek               text not null,
  author            text not null,
  role              text not null,
  date_label        text not null,
  reading_time      text not null,
  hero              text,
  pull_quote        text,
  -- How a piece finds its way into a relevant answer.
  tag_families      text[] not null default '{}',
  tag_subcategories text[] not null default '{}',
  body              jsonb not null default '[]'::jsonb,
  sort_order        smallint not null default 0
);

create index if not exists articles_families_idx on public.articles using gin (tag_families);
`)

// ——————————————————————————————————————— RLS

out.push(`-- ——— Row-level security ————————————————————————————————————
--
-- Read by anyone, written by nobody. Seeding happens through this file or the
-- service_role key, both of which bypass RLS.

do $$
declare t text;
begin
  foreach t in array array['categories', 'ingredients', 'certifications', 'products', 'articles']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "catalog: public read" on public.%I', t);
    execute format(
      'create policy "catalog: public read" on public.%I for select to anon, authenticated using (true)',
      t
    );
  end loop;
end $$;
`)

// ——————————————————————————————————————— Seed

out.push('-- ——— Seed ——————————————————————————————————————————————————\n')

out.push(
  upsert(
    'categories',
    'id',
    CATEGORIES.map((c, i) => ({
      id: lit(c.id),
      name: lit(c.name),
      subcategories: arr(c.subcategories),
      sort_order: String(i),
    })),
    ['id', 'name', 'subcategories', 'sort_order'],
  ),
)

out.push(
  upsert(
    'ingredients',
    'id',
    INGREDIENT_LIST.map((i) => ({
      id: lit(i.id),
      name: lit(i.name),
      aliases: arr(i.aliases),
      family: lit(i.family),
      level: lit(i.level),
      dimension: lit(i.dimension),
      confidence: lit(i.confidence),
      why: lit(i.why),
    })),
    ['id', 'name', 'aliases', 'family', 'level', 'dimension', 'confidence', 'why'],
  ),
)

out.push(
  upsert(
    'certifications',
    'id',
    CERT_LIST.map((c) => ({
      id: lit(c.id),
      name: lit(c.name),
      body: lit(c.body),
      rigor: lit(c.rigor),
      covers: lit(c.covers),
      what: lit(c.what),
    })),
    ['id', 'name', 'body', 'rigor', 'covers', 'what'],
  ),
)

out.push(
  upsert(
    'products',
    'id',
    PRODUCTS.map((p) => ({
      id: lit(p.id),
      name: lit(p.name),
      brand: lit(p.brand),
      category_id: lit(p.category),
      subcategory: lit(p.subcategory),
      tags: arr(p.tags),
      price: String(p.price),
      size: lit(p.size),
      ingredient_ids: arr(p.ingredients),
      certification_ids: arr(p.certifications),
      claim_ids: arr(p.claims),
      image: lit(p.image),
      summary: lit(p.summary),
    })),
    [
      'id', 'name', 'brand', 'category_id', 'subcategory', 'tags', 'price',
      'size', 'ingredient_ids', 'certification_ids', 'claim_ids', 'image',
      'summary',
    ],
  ),
)

out.push(
  upsert(
    'articles',
    'slug',
    ARTICLES.map((a, i) => ({
      slug: lit(a.slug),
      kicker: lit(a.kicker),
      title: lit(a.title),
      dek: lit(a.dek),
      author: lit(a.author),
      role: lit(a.role),
      date_label: lit(a.date),
      reading_time: lit(a.readingTime),
      hero: lit(a.hero),
      pull_quote: lit(a.pullQuote),
      tag_families: arr(a.tags.families),
      tag_subcategories: arr(a.tags.subcategories),
      body: jsonb(a.body),
      sort_order: String(i),
    })),
    [
      'slug', 'kicker', 'title', 'dek', 'author', 'role', 'date_label',
      'reading_time', 'hero', 'pull_quote', 'tag_families',
      'tag_subcategories', 'body', 'sort_order',
    ],
  ),
)

const sql = out.join('\n')
writeFileSync(new URL('../supabase/migrations/20260815120100_catalog.sql', import.meta.url), sql)

console.log(
  `supabase/migrations/20260815120100_catalog.sql written — ${CATEGORIES.length} categories, ` +
    `${INGREDIENT_LIST.length} ingredients, ${CERT_LIST.length} certifications, ` +
    `${PRODUCTS.length} products, ${ARTICLES.length} articles ` +
    `(${(sql.length / 1024).toFixed(1)} kB)`,
)
